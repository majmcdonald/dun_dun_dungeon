export function canDraw(text: string): boolean {
  return [...text.toUpperCase()].every((ch) => ch in GLYPHS);
}

export function textWidth(text: string, scale = 1): number {
  return text.length === 0 ? 0 : (text.length * CHAR_ADVANCE - 1) * scale;
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string = PALETTE.white,
  shadow: string | null = PALETTE.black,
  scale = 1,
): void {
  if (shadow) drawGlyphs(ctx, text, x + scale, y + scale, shadow, scale);
  drawGlyphs(ctx, text, x, y, color, scale);
}

function drawGlyphs(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  scale: number,
): void {
  ctx.fillStyle = color;
  const upper = text.toUpperCase();
  const ox = Math.round(x);
  const oy = Math.round(y);
  for (let i = 0; i < upper.length; i++) {
    const glyph = GLYPHS[upper[i]] ?? GLYPHS['?'];
    const gx = ox + i * CHAR_ADVANCE * scale;
    for (let row = 0; row < GLYPH_H; row++) {
      for (let col = 0; col < GLYPH_W; col++) {
        if (glyph[row][col] === '#') ctx.fillRect(gx + col * scale, oy + row * scale, scale, scale);
      }
    }
  }
}
