ROOT = os.path.join(os.path.dirname(__file__), '..', '..')
LEGEND = {
    'K': 'black', 'W': 'white', 'L': 'lightGray', 'M': 'gray', 'A': 'slate',
    'G': 'gold', 'Y': 'yellow', 'O': 'orange', 'T': 'tan', 'B': 'brown', 'b': 'darkBrown',
    'R': 'red', 'r': 'darkRed', 'C': 'cyan',
}
# Right halves of mirrored icons are shaded one step darker.
MIRROR_SHADE = {'L': 'M', 'W': 'L'}


def mirror(half, shade=True):
    rows = []
    for row in half:
        right = ''.join(MIRROR_SHADE.get(c, c) if shade else c for c in reversed(row))
        rows.append(row + right)
    return rows


def blank(size):
    return [['.'] * size for _ in range(size)]


def outline(rows):
    size = len(rows)
    g = [list(r) for r in rows]
    for y in range(size):
        for x in range(size):
            if rows[y][x] != '.':
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < size and 0 <= ny < size and rows[ny][nx] not in '.K':
                    g[y][x] = 'K'
                    break
    return [''.join(r) for r in g]


